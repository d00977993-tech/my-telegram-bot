@bot.message_handler(func=lambda m: True, content_types=["text"])
def handle_text(message):
    text = message.text.strip()
    chat_id = message.chat.id

    if chat_id not in user_data:
        user_data[chat_id] = {"step": "budget"}

    data = user_data[chat_id]
    step = data.get("step", "budget")

    if step == "budget":
        budget_num = parse_budget(text)
        if budget_num == 0:
            bot.send_message(chat_id, "🤔 Не похоже на бюджет. Напиши число — например: `5000` или `3к`.", parse_mode="Markdown")
            return

        data["budget_text"] = text
        data["budget_num"] = budget_num
        data["step"] = "direction"

        bot.send_message(
            chat_id,
            f"✅ Бюджет: *{text}*\n\nШаг 2 из 2. Напиши *направление* "
            f"(айти, инженерия, экология, робототехника, космос, медицина, физика, химия, математика).",
            parse_mode="Markdown",
        )
        return

    if step == "direction":
        if parse_budget(text) > 0 and not any(ch.isalpha() for ch in text):
            bot.send_message(chat_id, "🤔 Это похоже на бюджет. Напиши направление *словами*.", parse_mode="Markdown")
            return

        data["direction"] = text
        result_text, ideas = generate_ideas(data["budget_num"], data["budget_text"], text)
        last_ideas[chat_id] = ideas

        markup = types.InlineKeyboardMarkup(row_width=1)
        for i, idea in enumerate(ideas, 1):
            short_name = idea[1][:45]
            markup.add(types.InlineKeyboardButton(
                text=f"📖 {i}. {short_name}",
                callback_data=f"detail_{i-1}"
            ))

        bot.send_message(chat_id, result_text, parse_mode="Markdown", reply_markup=markup)
        bot.send_message(chat_id, "👇 Нажми на кнопку, чтобы увидеть подробный план.")

        user_data[chat_id] = {"step": "budget"}
        return

